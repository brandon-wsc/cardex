#!/usr/bin/env bash
# Rebuild seed/seed.sql from prod D1.
#
# Facts tables are dumped verbatim. reports/proposals stay out: reports are
# quarantined public submissions and proposals are the audit trail — neither
# belongs in a committed snapshot. Local-dev fixtures for those two tables
# are appended from seed/fixtures.sql instead.
set -euo pipefail

cd "$(dirname "$0")/.."

FACTS_TABLES=(meta cards tags rates rate_tags terms rate_terms term_merchants aliases alias_tags alias_cards)
# All tables, children before parents, matching migration FK order.
ALL_TABLES=(rate_terms rate_tags alias_tags alias_cards aliases term_merchants terms rates tags cards reports proposals meta)

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

args=(d1 export cardex-db --remote --no-schema -y --output "$tmp")
for t in "${FACTS_TABLES[@]}"; do
  args+=(--table "$t")
done

pnpm --dir packages/mcp-worker exec wrangler "${args[@]}"

{
  # No date stamp here: the commit records when, and a stamped header would
  # diff every run even when the facts did not drift.
  echo "-- GENERATED by scripts/export-seed.sh — do not edit by hand."
  echo "-- Facts dumped from prod D1; reports/proposals are local-dev fixtures"
  echo "-- appended from seed/fixtures.sql. Idempotent: clears and re-inserts."
  echo
  for t in "${ALL_TABLES[@]}"; do
    echo "DELETE FROM $t;"
  done
  echo
  cat "$tmp"
  echo
  cat seed/fixtures.sql
} > seed/seed.sql

echo "wrote seed/seed.sql"
