// Render docs/dup-baseline/baseline.md from the jscpd JSON report and
// normalize the JSON so `pnpm dup` re-runs produce stable diffs.
// Run via the root script: pnpm dup
import { readFileSync, writeFileSync } from "node:fs";

const SCAN_ROOT = "packages/mcp-worker/src";
const OUT_DIR = "docs/dup-baseline";

const reportPath = `${OUT_DIR}/jscpd-report.json`;
const report = JSON.parse(readFileSync(reportPath, "utf8"));

delete report.statistics?.detectionDate;
for (const stats of Object.values(report.statistics?.formats ?? {})) {
  delete stats.detectionDate;
}
report.duplicates.sort(
  (a, b) =>
    a.firstFile.name.localeCompare(b.firstFile.name) ||
    a.firstFile.start - b.firstFile.start ||
    a.secondFile.name.localeCompare(b.secondFile.name) ||
    a.secondFile.start - b.secondFile.start,
);
writeFileSync(reportPath, `${JSON.stringify(report, null, 2)}\n`);

const jscpdVersion = JSON.parse(readFileSync("package.json", "utf8")).devDependencies.jscpd;
const isSpec = (name) => /\.(test|spec)\.[tj]sx?$/.test(name);
const loc = (f) => `\`${SCAN_ROOT}/${f.name}:${f.start}-${f.end}\``;
const pct = (n) => n.toFixed(2);

const total = report.statistics.total;
const prod = report.duplicates.filter((d) => !isSpec(d.firstFile.name) && !isSpec(d.secondFile.name));
const specs = report.duplicates.filter((d) => isSpec(d.firstFile.name) || isSpec(d.secondFile.name));

const row = (d, i) => `| ${i + 1} | ${loc(d.firstFile)} | ${loc(d.secondFile)} | ${d.lines} | ${d.tokens} | ${d.kind} |`;
const table = (dups) =>
  dups.length === 0
    ? "None.\n"
    : `| # | First fragment | Second fragment | Lines | Tokens | Kind |\n|---|----------------|-----------------|-------|--------|------|\n${dups.map(row).join("\n")}\n`;

const md = `# Duplication baseline — mcp-worker

Generated by \`pnpm dup\` ([jscpd](https://github.com/kucherenko/jscpd) ${jscpdVersion},
config in \`.jscpd.json\`). Do not edit by hand — re-run \`pnpm dup\`.

Scope: \`${SCAN_ROOT}/**/*.{ts,tsx}\` — production sources and the specs that
live beside them. Defaults: min-tokens 50, min-lines 5.

| Files scanned | Lines | Tokens | Clones | Duplicated lines | Duplicated tokens |
|---------------|-------|--------|--------|------------------|-------------------|
| ${total.sources} | ${total.lines} | ${total.tokens} | ${total.clones} | ${total.duplicatedLines} (${pct(total.percentage)}%) | ${total.duplicatedTokens} (${pct(total.percentageTokens)}%) |

## Production clones

Clones where neither fragment is a spec file.

${table(prod)}
## Spec clones

Clones touching \`*.test.ts\` / \`*.spec.ts\`. Usually repeated fixtures or
assertion blocks; tracked separately so spec boilerplate does not mask
production duplication.

${table(specs)}
---
Advisory only — nothing in this report gates CI. See \`README.md\` in this
directory for scope and policy.
`;

writeFileSync(`${OUT_DIR}/baseline.md`, md);
console.log(`wrote ${OUT_DIR}/baseline.md and normalized ${reportPath}`);
